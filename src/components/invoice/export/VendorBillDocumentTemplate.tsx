import * as React from "react";
import { FASTRASUITE_LOGO_BASE64 } from "@/components/project-costing/export/ExecutiveProjectReportTemplate";
import { VendorBill, VendorBillLine } from "@/api/invoice/vendorBillsApi";

export interface VendorBillDocumentTemplateProps {
  bill?: VendorBill | any | null;
  companyName?: string;
  companyAddress?: string;
  companyPhone?: string;
  companyLogo?: string;
}

const formatCurrency = (amount: number): string => {
  if (isNaN(amount)) return "₦0";
  return `₦${Math.round(amount).toLocaleString("en-US")}`;
};

const formatDateDDMMYYYY = (dateStr?: string | null): string => {
  if (!dateStr) return "—";
  try {
    const d = new Date(dateStr);
    if (isNaN(d.getTime())) return String(dateStr);
    const day = String(d.getDate()).padStart(2, "0");
    const month = String(d.getMonth() + 1).padStart(2, "0");
    const year = d.getFullYear();
    return `${day}/${month}/${year}`;
  } catch {
    return String(dateStr);
  }
};

export const VendorBillDocumentTemplate: React.FC<VendorBillDocumentTemplateProps> = ({
  bill,
  companyName = "FastraSuite",
  companyAddress = "",
  companyPhone = "",
  companyLogo = "",
}) => {
  // 1. Resolve header fields
  const billNumber = bill?.bill_number || (bill?.id ? `VB-${bill.id}` : "BCM-INV-11084");
  const billDate = formatDateDDMMYYYY(bill?.invoice_date || bill?.created_at || new Date().toISOString());
  const dueDate = formatDateDDMMYYYY(bill?.due_date);

  // 2. Resolve vendor details
  const vendorName =
    bill?.vendor_details?.vendor_name ||
    bill?.vendor_name ||
    (bill as any)?.vendor?.name ||
    "—";

  const vendorDetailsLine = React.useMemo(() => {
    const vd = bill?.vendor_details || (bill as any)?.vendor || {};
    const parts = [
      vd.address || vd.street_address || vd.city,
      vd.email || bill?.vendor_email,
      vd.phone_number || vd.phone || bill?.vendor_phone,
    ].filter(Boolean);

    if (parts.length > 0) return parts.join(" · ");
    return "";
  }, [bill]);

  // 3. Resolve 4-Column Key Metrics Bar
  // Column 1: PO Reference (displayed as PO-YYYY-XXXXX)
  const poReference =
    bill?.purchase_order ||
    (bill?.project_purchase_order ? `PO-${bill.project_purchase_order}` : null) ||
    bill?.source_details?.project_purchase_order?.po_number ||
    (bill as any)?.po_number ||
    (bill?.bill_number ? `PO-${bill.bill_number.replace(/^[A-Za-z]+-?/, "")}` : "—");

  // Column 2: Payment Terms
  const paymentTerms = React.useMemo(() => {
    if (bill?.payment_term_details?.name) return bill.payment_term_details.name;
    if (bill?.payment_term) return `Net ${bill.payment_term} days`;
    if ((bill as any)?.payment_terms) return (bill as any).payment_terms;
    return "Net 30 days";
  }, [bill]);

  // Column 3: Invoice Received Date
  const invoiceReceivedDate = formatDateDDMMYYYY(bill?.invoice_date || bill?.created_at || new Date().toISOString());

  // Column 4: Generated By
  const generatedBy = React.useMemo(() => {
    if (bill?.approved_by_details) {
      const full = `${bill.approved_by_details.first_name || ""} ${bill.approved_by_details.last_name || ""}`.trim();
      if (full) return full;
      if (bill.approved_by_details.email) return bill.approved_by_details.email;
    }
    if ((bill as any)?.created_by_details) {
      const full = `${(bill as any).created_by_details.first_name || ""} ${(bill as any).created_by_details.last_name || ""}`.trim();
      if (full) return full;
    }
    if ((bill as any)?.approved_by_name) return (bill as any).approved_by_name;
    return "Operations";
  }, [bill]);

  // 4. Resolve Line items
  const taxRate = 0.075; // 7.5% standard VAT

  const lines: VendorBillLine[] = React.useMemo(() => {
    if (Array.isArray(bill?.lines) && bill.lines.length > 0) {
      return bill.lines;
    }
    const rawTotal = Number(bill?.amount || 0);
    if (rawTotal > 0) {
      return [
        {
          project_purchase_order_line: null,
          purchase_order_line: null,
          labour_request: null,
          subcontractor_milestone: null,
          subcontractor_request: null,
          description:
            (bill as any)?.source_type_display ||
            (bill as any)?.description ||
            `Vendor Bill - ${billNumber}`,
          quantity: "1",
          unit_price: String(Math.round(rawTotal / (1 + taxRate))),
          unit: "Lot",
          line_total: rawTotal,
        } as any,
      ];
    }
    return [];
  }, [bill, billNumber]);

  // 5. Calculations
  const rawTotal = Number(bill?.amount || 0);

  const subtotal = React.useMemo(() => {
    if (lines.length > 0) {
      return lines.reduce((acc, l) => {
        const q = Number(l.quantity || 1);
        const p = Number(l.unit_price || 0);
        return acc + q * p;
      }, 0);
    }
    return rawTotal > 0 ? Math.round(rawTotal / (1 + taxRate)) : 0;
  }, [lines, rawTotal]);

  const taxAmount = Math.round(subtotal * taxRate);
  const grandTotal = rawTotal > 0 ? rawTotal : subtotal + taxAmount;

  return (
    <div
      style={{
        width: "820px",
        minHeight: "1160px",
        backgroundColor: "#ffffff",
        color: "#111827",
        fontFamily: "'Open Sans', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif",
        padding: "40px 45px",
        boxSizing: "border-box",
        position: "relative",
        display: "flex",
        flexDirection: "column",
        justifyContent: "space-between",
      }}
    >
      <div>
        {/* ================= 1. HEADER ================= */}
        <div className="flex items-start justify-between">
          {/* Company Brand Logo / Badge */}
          <div>
            {companyLogo ? (
              <img
                src={companyLogo}
                alt={companyName}
                crossOrigin="anonymous"
                className="h-10 w-auto object-contain"
                onError={(e) => {
                  (e.target as HTMLElement).style.display = "none";
                }}
              />
            ) : companyName ? (
              <div className="h-10 px-3 bg-gray-900 text-white rounded-md flex items-center justify-center font-bold text-sm tracking-tight shadow-xs">
                {companyName}
              </div>
            ) : (
              <div className="h-10 px-3 bg-gray-100 border border-gray-200 text-gray-700 rounded-md flex items-center justify-center font-bold text-sm tracking-tight shadow-xs">
                FastraSuite
              </div>
            )}
          </div>

          {/* Company Contact Details */}
          <div className="text-right">
            <h2 className="text-[15px] font-bold text-gray-900 leading-snug">
              {companyName || "FastraSuite"}
            </h2>
            {companyAddress ? (
              <p className="text-[11px] text-gray-500 leading-tight mt-0.5">
                {companyAddress}
              </p>
            ) : null}
            {companyPhone ? (
              <p className="text-[11px] text-gray-500 leading-tight mt-0.5">
                Contact: {companyPhone}
              </p>
            ) : null}
          </div>
        </div>

        {/* Title & Bill Meta */}
        <div className="mt-6">
          <h1 className="text-[26px] font-extrabold text-gray-900 tracking-tight leading-none">
            Vendor Bill
          </h1>
          <div className="flex flex-wrap items-center gap-x-6 gap-y-1 mt-2.5 text-[12.5px] text-gray-700">
            <div>
              <span className="font-semibold text-gray-900">Vendor invoice:</span>{" "}
              <span>{billNumber}</span>
            </div>
            <div>
              <span className="font-semibold text-gray-900">Bill date:</span>{" "}
              <span>{billDate}</span>
            </div>
          </div>
          <div className="mt-1.5 text-[12.5px] text-gray-700">
            <span className="font-semibold text-gray-900">Due date:</span>{" "}
            <span>{dueDate}</span>
          </div>
        </div>

        {/* Solid Blue Horizontal Divider */}
        <div className="w-full h-[2.5px] bg-[#0D3C8C] mt-3.5 mb-5" />

        {/* ================= 2. VENDOR INFORMATION ================= */}
        <div>
          <h3 className="text-[10px] font-bold text-[#0D3C8C] tracking-wider uppercase mb-1">
            VENDOR INFORMATION
          </h3>
          <h4 className="text-[13.5px] font-bold text-gray-900 leading-tight">
            {vendorName}
          </h4>
          {vendorDetailsLine ? (
            <p className="text-[11px] text-gray-500 mt-0.5 leading-snug">
              {vendorDetailsLine}
            </p>
          ) : null}
        </div>

        {/* ================= 3. 4-COLUMN KEY METRICS BAR ================= */}
        <div className="rounded-lg bg-[#F5F8FF] border border-blue-100/60 p-3.5 grid grid-cols-4 divide-x divide-gray-200 mt-5">
          <div className="pr-3">
            <div className="text-[9px] font-bold text-gray-400 tracking-wider uppercase">
              PAYMENT TERMS
            </div>
            <div className="text-[12.5px] font-bold text-gray-900 mt-1 truncate">
              {poReference}
            </div>
          </div>

          <div className="px-3">
            <div className="text-[9px] font-bold text-gray-400 tracking-wider uppercase">
              PAYMENT TERMS
            </div>
            <div className="text-[12.5px] font-bold text-gray-900 mt-1 truncate">
              {paymentTerms}
            </div>
          </div>

          <div className="px-3">
            <div className="text-[9px] font-bold text-gray-400 tracking-wider uppercase">
              INVOICE RECEIVED
            </div>
            <div className="text-[12.5px] font-bold text-gray-900 mt-1 truncate">
              {invoiceReceivedDate}
            </div>
          </div>

          <div className="pl-3">
            <div className="text-[9px] font-bold text-gray-400 tracking-wider uppercase">
              GENERATED BY
            </div>
            <div className="text-[12.5px] font-bold text-gray-900 mt-1 truncate">
              {generatedBy}
            </div>
          </div>
        </div>

        {/* ================= 4. BILL DETAILS TABLE ================= */}
        <div className="mt-6">
          <h3 className="text-[10px] font-bold text-[#0D3C8C] tracking-wider uppercase mb-2">
            BILL DETAILS
          </h3>

          <div className="border border-gray-200 rounded-lg overflow-hidden">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="bg-[#F5F8FF] border-b border-gray-200 text-gray-500 text-[10px] font-semibold">
                  <th className="py-2.5 px-4 font-semibold">Description</th>
                  <th className="py-2.5 px-3 text-center font-semibold w-16">Qty</th>
                  <th className="py-2.5 px-3 text-left font-semibold w-20">Unit</th>
                  <th className="py-2.5 px-4 text-right font-semibold w-28">Unit price</th>
                  <th className="py-2.5 px-3 text-center font-semibold w-20">Tax</th>
                  <th className="py-2.5 px-4 text-right font-semibold w-32">Amount</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-100 text-[11px] text-gray-800">
                {lines.length === 0 ? (
                  <tr>
                    <td colSpan={6} className="py-6 text-center text-gray-400 italic">
                      No line items recorded for this vendor bill.
                    </td>
                  </tr>
                ) : (
                  lines.map((item: any, idx: number) => {
                    const qty = Number(item.quantity || 1);
                    const rate = Number(item.unit_price || 0);
                    const lineTotal = Number(item.line_total || qty * rate * (1 + taxRate));

                    return (
                      <tr key={idx} className="hover:bg-gray-50/50">
                        <td className="py-3 px-4 font-medium text-gray-800">
                          {item.description || item.item_name || "—"}
                        </td>
                        <td className="py-3 px-3 text-center text-gray-800 font-medium">
                          {qty}
                        </td>
                        <td className="py-3 px-3 text-left text-gray-600">
                          {item.unit || "Lot"}
                        </td>
                        <td className="py-3 px-4 text-right font-semibold text-gray-800">
                          {formatCurrency(rate)}
                        </td>
                        <td className="py-3 px-3 text-center text-gray-600">
                          7.5%
                        </td>
                        <td className="py-3 px-4 text-right font-semibold text-gray-900">
                          {formatCurrency(lineTotal)}
                        </td>
                      </tr>
                    );
                  })
                )}
              </tbody>
            </table>
          </div>
        </div>

        {/* ================= 5. PAYMENT INFORMATION + TOTALS ================= */}
        <div className="flex justify-between items-start mt-6 gap-8">
          {/* Left: Payment Information Card */}
          <div className="flex-1 max-w-[420px] rounded-lg bg-[#F5F8FF] border border-blue-100/60 p-3.5">
            <h3 className="text-[10px] font-bold text-[#0D3C8C] tracking-wider uppercase mb-1.5">
              PAYMENT INFORMATION
            </h3>
            <p className="text-[11.5px] leading-relaxed text-gray-600">
              Payment is due by <span className="font-semibold text-gray-800">{dueDate}</span> in line with the agreed {paymentTerms} terms. Please quote the bill number on all payment correspondence.
            </p>
          </div>

          {/* Right: Summary Box with Deep Royal Blue Total Banner */}
          <div className="w-[280px]">
            <div className="flex justify-between items-center text-[12px] py-1 border-b border-gray-100">
              <span className="text-gray-600 font-medium">Subtotal</span>
              <span className="font-bold text-gray-900">{formatCurrency(subtotal)}</span>
            </div>
            <div className="flex justify-between items-center text-[12px] py-1 mt-1">
              <span className="text-gray-600 font-medium">Tax (7.5%)</span>
              <span className="font-bold text-gray-900">{formatCurrency(taxAmount)}</span>
            </div>
            {/* Deep Royal Blue Total Box */}
            <div className="bg-[#0D3C8C] rounded-md px-4 py-3 text-white flex justify-between items-center mt-3 shadow-xs">
              <span className="text-[13px] font-bold uppercase tracking-wider text-white">
                Total
              </span>
              <span className="text-[16px] font-extrabold text-white tracking-tight">
                {formatCurrency(grandTotal)}
              </span>
            </div>
          </div>
        </div>

        {/* ================= 6. TERMS AND CONDITIONS ================= */}
        <div className="mt-8">
          <h5 className="text-[9px] font-bold text-gray-500 mb-1">Terms and Conditions</h5>
          <ol className="text-[8px] leading-[1.38] text-gray-400 space-y-0.5 list-decimal pl-3.5">
            <li>This order is based on the items, quantities, prices, delivery date and payment terms stated on this Purchase Order.</li>
            <li>The Vendor confirms acceptance of this order by signing and returning a copy, or by confirming in writing.</li>
            <li>Any change to price, quantity, specification or delivery date should be agreed with {companyName || "FastraSuite"} in writing before it takes effect.</li>
            <li>Goods or services should be delivered as stated on this order. The Vendor should tell {companyName || "FastraSuite"} promptly if delivery will be late or if any part of the order cannot be supplied as specified.</li>
            <li>Deliveries are checked on receipt, and any difference from this order is raised with the Vendor.</li>
            <li>Invoices should quote this Purchase Order number and match the items, quantities and prices on it. Any difference should be explained in writing.</li>
            <li>Payment is made against this Purchase Order, to the Vendor&apos;s bank account on record, in line with the payment terms stated on it.</li>
          </ol>
        </div>

        {/* ================= 7. SIGN-OFF SIGNATURE LINES ================= */}
        <div className="grid grid-cols-2 gap-8 mt-6 pt-1 text-[9.5px] text-gray-600 font-medium">
          <div className="flex items-center gap-2">
            <span>Approved By</span>
            <span className="border-b border-dotted border-gray-400 flex-1 h-3" />
            <span className="ml-2">Date</span>
            <span className="border-b border-dotted border-gray-400 w-24 h-3" />
          </div>
          <div className="flex items-center gap-2">
            <span>Vendor Signature</span>
            <span className="border-b border-dotted border-gray-400 flex-1 h-3" />
            <span className="ml-2">Date</span>
            <span className="border-b border-dotted border-gray-400 w-24 h-3" />
          </div>
        </div>
      </div>

      {/* ================= 8. FOOTER ================= */}
      <div className="border-t border-gray-200 pt-3 mt-6 flex items-center justify-between text-[8.5px] text-gray-400">
        <div className="flex items-center">
          <img
            src={FASTRASUITE_LOGO_BASE64}
            alt="FastraSuite"
            className="h-5 w-auto object-contain"
          />
        </div>

        <div className="tracking-wider uppercase font-medium text-[8px] text-gray-400">
          GENERATED VIA FASTRASUITE—NIGERIA&apos;S TRUSTED PROJECT COSTING PLATFORM.
        </div>

        <div className="font-medium text-gray-400">
          Page 1 of 1
        </div>
      </div>
    </div>
  );
};
